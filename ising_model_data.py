import numpy as np
from scipy.linalg import eigh
"""
This synthetic dataset is generated by modeling a real system's evolution and pairing the resulting ground states with 
the dominant phase: g < 1.0 implies ferromagnetic phase where spin-spin interaction dominates
g > 1.0 paramagnetic phase--the external transverse field dominates

Basically what model we should use to model the particle. The system can be modeled as qubits so the evolution can be modeled using
linear operators when the ground state function
"""

# Pauli matrices
X = np.array([[0, 1], [1, 0]])
Z = np.array([[1, 0], [0, -1]])
I = np.eye(2)

# 2-qubit Hamiltonian terms
ZZ = np.kron(Z, Z)
X_total = np.kron(X, I) + np.kron(I, X)

def get_tfim_ground_state(g, J=1.0):
    # H = -J * Z_0 Z_1 - g * (X_0 + X_1)
    H = -J * ZZ - g * X_total
    evals, evecs = eigh(H)
    return evecs[:, 0]  # Ground state vector (4 dimensional)

def generate_dataset(samples):
    # Generate dataset across different values of transverse field g
    g_values = np.linspace(0.1, 2.0, 100)
    X_data = []
    y_data = []

    for g in g_values:
        psi_0 = get_tfim_ground_state(g)
        X_data.append(psi_0)  # Shape (4,) amplitude vector
        y_data.append(1 if g < 1.0 else 0)  # Binary classification label

    X_data = np.array(X_data)
    y_data = np.array(y_data)
    
    return X_data, y_data